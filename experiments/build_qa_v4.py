def _row(age, tbl):
    for (lo, hi), r in tbl.items():
        if lo <= age <= hi:
            return r


def price(age, social, tbl):
    return float(_row(age, tbl)["必选计划_有社保" if social else "必选计划_无社保"])


def addon(age, col, tbl):
    return float(_row(age, tbl)[col])


def nre(v):
    s = f"{v:g}"
    if "." in s:
        return rf"(?<![\d.]){re.escape(s)}(?!\d)"
    return rf"(?<!\d){s}(\.0)?(?!\d)" if len(s) < 4 else rf"(?<!\d){s[:-3]},?{s[-3:]}(?!\d)"


