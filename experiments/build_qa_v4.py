def _norm(s):
    return re.sub(r"[\s，。？！、,.?!“”\"']", "", s)


def check():
    old = []
    for fn in ("qa_v2.json", "qa_v3.json"):
        for it in json.loads((ROOT / "experiments" / "data" / fn).read_text(encoding="utf-8")):
            old.append((it["id"], " → ".join(it["turns"]) if it.get("turns") else it["question"]))
    seen, flagged = {}, []
    for it in items:
        q = " → ".join(it["turns"]) if it["turns"] else it["question"]
        assert _norm(q) not in seen, f"duplicate inside v4: {q}"
        seen[_norm(q)] = it["id"]
        best = max(old, key=lambda o: difflib.SequenceMatcher(None, _norm(q), _norm(o[1])).ratio())
        r = difflib.SequenceMatcher(None, _norm(q), _norm(best[1])).ratio()
        print(f"{it['id']} {r:.2f} {q}  <->  {best[0]} {best[1]}")
        if r >= 0.75:
            flagged.append((it["id"], r, q, best))
        for p in it["must"] + it["must_not"]:
            re.compile(p)
        # 价格类：facts 中的每个金额必须被 must 命中、不被 must_not 命中
        for v in re.findall(r"缴(\d+(?:\.\d+)?)", it["facts"]):
            f = float(v)
            for t in (f"{f:g}元", f"{f:,.0f}元" if f == int(f) else f"{f:g}元", f"一年是{f:g}元。", f"{f:.1f}元"):
                assert any(re.search(p, t) for p in it["must"]), (it["id"], v, t)
                assert not any(re.search(p, t) for p in it["must_not"]), (it["id"], v, t)
    print("near-duplicates (ratio>=0.75):", flagged or "none")
    return flagged


def main():
    for i, it in enumerate(items):
        it["id"] = f"W{i + 1:03d}"
    check()
    OUT.write_text(json.dumps(items, ensure_ascii=False, indent=1), encoding="utf-8")
    print(len(items), collections.Counter(i["category"] for i in items))


if __name__ == "__main__":
    main()
