def _table(name):
    with (ROOT / "data" / "clean" / "premium" / f"{name}.csv").open(encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    head = rows[0][1:]
    return {tuple(int(x) for x in r[0].strip("[]").split(",")): dict(zip(head, r[1:])) for r in rows[1:]}


