def _table(name):
    with (PREMIUM / f"{name}.csv").open(encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    out = {}
    for r in rows[1:]:
        lo, hi = (int(x) for x in r[0].strip("[]").split(","))
        out[(lo, hi)] = dict(zip(rows[0][1:], r[1:]))
    return out


