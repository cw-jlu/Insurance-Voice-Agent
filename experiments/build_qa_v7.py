def main():
    for i, it in enumerate(items):
        it["id"] = f"Y{i + 1:03d}"
    old = set()
    for p in ("qa_v2.json", "qa_v3.json", "qa_v4.json", "qa_v5.json", "qa_v6.json"):
        old |= {x["question"] for x in json.loads((ROOT / "experiments" / "data" / p).read_text(encoding="utf-8"))}
    dup = [i["question"] for i in items if i["question"] in old]
    assert not dup, dup
    OUT.write_text(json.dumps(items, ensure_ascii=False, indent=1), encoding="utf-8")
    import collections
    print(len(items), collections.Counter(i["group"] for i in items))


if __name__ == "__main__":
    main()
