ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "experiments" / "data" / "qa_v3.json"
NOT = r"不(予|能|在|会)?(理赔|报|赔|保障|承担)|免责|除外|不属于"
UW = r"健康告知|核保"
CONFIRM = r"条款|专员|人工|确认"


def _table(name):
    with (ROOT / "data" / "clean" / "premium" / f"{name}.csv").open(encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    return {tuple(int(x) for x in r[0].strip("[]").split(",")): r[1:] for r in rows[1:]}


Y, M = _table("年缴_必选"), _table("月缴_必选")


def price(age, social, tbl):
    for (lo, hi), r in tbl.items():
        if lo <= age <= hi:
            return float(r[0 if social else 1])


def nre(v):
    s = f"{v:g}"
    return rf"(?<!\d){s}(\.0)?(?!\d)" if len(s) < 4 else rf"(?<!\d){s[:-3]},?{s[-3:]}(?!\d)"


items = []


def add(cat, q, must=(), must_not=(), facts="", context=None, turns=None):
    items.append({"category": cat, "question": q, "must": list(must), "must_not": list(must_not), "facts": facts,
                  "context": context or {}, "turns": turns, "source": "v3", "split": "heldout", "valid": True})


