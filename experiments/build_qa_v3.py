# 价格（新种子抽样）
rng = random.Random(20261010)
for _ in range(24):
    age = rng.choice([2, 6, 9, 12, 14, 19, 22, 24, 27, 29, 32, 34, 37, 39, 42, 44, 47, 49, 52, 54, 57, 59, 62, 64, 67, 69])
    social = rng.random() < 0.55
    pay = "月缴" if rng.random() < 0.35 else "年缴"
    who = "我孩子" if age < 18 else rng.choice(["我", "我老公", "我老婆"]) if age < 45 else rng.choice(["我", "我爸", "我妈"])
    s_txt = rng.choice(["有社保", "交了医保", "有职工医保"]) if social else rng.choice(["没社保", "医保断交了", "没有医保"])
    p_txt = "每月要交多少" if pay == "月缴" else rng.choice(["一年多少钱", "年交多少"])
    v = price(age, social, M if pay == "月缴" else Y)
    add("价格", f"{who}今年{age}岁，{s_txt}，{p_txt}", [nre(v)], [nre(price(age, not social, M if pay == "月缴" else Y))],
        f"{age}岁{'有' if social else '无'}社保{pay}{v:g}元")
add("价格", "这个保险贵不贵，大概多少", [r"年龄|年纪|多大|几岁|社保"], [r"\d{3,}\s*元"], "缺条件应追问")
